#!/usr/bin/env node
// Regenerates battles/index.md — the LLM Wiki catalog — from every page's
// frontmatter, so the index can never drift from the pages it lists.
// Also reports broken [[wikilinks]].
// Usage: node scripts/build-battle-index.mjs [--check]   (--check: exit 1 if index.md is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'battles');
const wiki = path.join(root, 'wiki');

function frontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const out = {};
  if (!m) return out;
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if (v.startsWith('[') && v.endsWith(']')) {
      v = v
        .slice(1, -1)
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean);
    }
    out[kv[1]] = v;
  }
  return out;
}

/** First "> " summary line, or the first prose paragraph after the H1. */
function summary(text) {
  const body = text.replace(/^---[\s\S]*?---/, '');
  const quote = /^>\s*(.+)$/m.exec(body);
  const para =
    quote?.[1] ?? body.split(/\r?\n\r?\n/).find((p) => p.trim() && !/^[#>-]/.test(p.trim()));
  const s = (para ?? '')
    .replace(/\[\[([^\]]+)\]\]/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
  const sentence = /^(.{40,240}?[.!?])(\s|$)/.exec(s)?.[1] ?? s.slice(0, 200);
  return sentence;
}

function pages(dir) {
  const d = path.join(wiki, dir);
  if (!fs.existsSync(d)) return [];
  return fs
    .readdirSync(d)
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const text = fs.readFileSync(path.join(d, f), 'utf8');
      return {
        slug: path.basename(f, '.md'),
        file: `wiki/${dir}/${f}`,
        fm: frontmatter(text),
        text,
      };
    });
}

const battles = pages('battles');
const commanders = pages('commanders');
const concepts = pages('concepts');
const all = new Set([...battles, ...commanders, ...concepts].map((p) => p.slug));

/** Chronological key from the scenario's `year` ("490 BCE" → -490, "1942–1943 CE" → 1942). */
const yearOf = (p) => {
  let s = '';
  try {
    s = String(
      JSON.parse(fs.readFileSync(path.join(root, 'scenarios', `${p.slug}.json`), 'utf8')).year,
    );
  } catch {
    s = String(p.fm.date ?? '');
  }
  const n = parseInt(/(\d+)/.exec(s)?.[1] ?? '0', 10);
  return /BCE|BC/.test(s) ? -n : n;
};
battles.sort((a, b) => yearOf(a) - yearOf(b));
commanders.sort((a, b) => a.slug.localeCompare(b.slug));
concepts.sort((a, b) => a.slug.localeCompare(b.slug));

const list = (v) => (Array.isArray(v) ? v : v ? [v] : []);
const lines = [
  '# Battle Wiki — Index',
  '',
  '> Catalog of every page in this wiki, one line each. Read this first. Generated by',
  '> `node scripts/build-battle-index.mjs` from page frontmatter — edit the pages, not this file.',
  '> Conventions: [SCHEMA.md](SCHEMA.md). History of changes: [log.md](log.md).',
  '> Raw source: [OldBatles1.md](OldBatles1.md) (immutable).',
  '',
  `## Battles (${battles.length})`,
  '',
  '| Battle | Date | Victor | Scenario | Summary |',
  '| ------ | ---- | ------ | -------- | ------- |',
  ...battles.map(
    (p) =>
      `| [${p.fm.title ?? p.slug}](${p.file}) | ${p.fm.date ?? ''} | ${p.fm.victor ?? ''} | [${p.slug}.json](scenarios/${p.slug}.json) | ${summary(p.text).replace(/\|/g, '/')} |`,
  ),
  '',
  `## Commanders (${commanders.length})`,
  '',
  ...commanders.map(
    (p) =>
      `- [${p.fm.name ?? p.slug}](${p.file}) — ${[p.fm.allegiance, p.fm.lifespan].filter(Boolean).join(', ')}; battles: ${list(
        p.fm.battles,
      )
        .map((b) => `[[${b}]]`)
        .join(', ')}`,
  ),
  '',
  `## Concepts (${concepts.length})`,
  '',
  ...concepts.map(
    (p) =>
      `- [${p.fm.name ?? p.slug}](${p.file}) — ${summary(p.text)} Battles: ${list(p.fm.battles)
        .map((b) => `[[${b}]]`)
        .join(', ')}`,
  ),
  '',
];
const index = lines.join('\n');

// Broken wikilinks: a [[slug]] with no page is a page worth writing later.
const missing = new Map();
for (const p of [...battles, ...commanders, ...concepts]) {
  for (const m of p.text.matchAll(/\[\[([^\]|#]+)(?:[|#][^\]]*)?\]\]/g)) {
    const slug = m[1].trim();
    if (!all.has(slug)) missing.set(slug, [...(missing.get(slug) ?? []), p.slug]);
  }
}

const target = path.join(root, 'index.md');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== index) {
    console.error('battles/index.md is stale — run: node scripts/build-battle-index.mjs');
    process.exit(1);
  }
  console.log('battles/index.md is up to date.');
} else {
  fs.writeFileSync(target, index);
  console.log(
    `Wrote battles/index.md: ${battles.length} battles, ${commanders.length} commanders, ${concepts.length} concepts.`,
  );
}
if (missing.size) {
  console.log(`Wikilinks without a page yet (${missing.size}):`);
  for (const [slug, from] of missing)
    console.log(`  [[${slug}]] ← ${[...new Set(from)].join(', ')}`);
}
